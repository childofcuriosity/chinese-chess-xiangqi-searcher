"""Generate checked-in NNUE result tables and dependency-free SVG curves."""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path


HERE = Path(__file__).resolve().parent
SLIDES_NNUE_ASSETS = HERE.parent / "slides-formal-web-lite" / "assets" / "nnue"


def load(name: str):
    return json.loads((HERE / name).read_text(encoding="utf-8"))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest().upper()


def performance_elo(result: dict, opponent_elo: float) -> float:
    score = result["a_score"] / (result["a_score"] + result["b_score"])
    return opponent_elo + 400.0 * math.log10(score / (1.0 - score))


def check_artifacts() -> None:
    manifest = load("artifacts.json")
    entries = [
        manifest["model"],
        manifest["iteration1_model"],
        manifest["candidate_model"],
        manifest["iteration3_model"],
        *manifest["source"].values(),
        *manifest["data"].values(),
    ]
    checked = 0
    for entry in entries:
        path = (HERE / entry["file"]).resolve()
        if not path.exists():
            if entry.get("distributed_in_git") is False:
                print(f"optional artifact absent: {path.name}")
                continue
            raise FileNotFoundError(path)
        actual = sha256(path)
        expected = entry["sha256"].upper()
        if actual != expected:
            raise ValueError(f"SHA-256 mismatch for {path}: {actual} != {expected}")
        if "bytes" in entry and path.stat().st_size != entry["bytes"]:
            raise ValueError(f"size mismatch for {path}")
        print(f"artifact ok: {path.name}")
        checked += 1
    print(f"verified {checked} available artifacts")


def markdown_report() -> str:
    comparison = load("model_comparison.json")
    direct = load("direct_match_summary.json")
    iterations = [
        load("iter1_experiment.json"),
        load("iter2_experiment.json"),
        load("iter3_experiment.json"),
    ]
    swiss = load("swiss_8models_5rounds.json")
