"""Generate checked-in NNUE result tables and dependency-free SVG curves."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent


def load(name: str):
    return json.loads((HERE / name).read_text(encoding="utf-8"))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest().upper()


def check_artifacts() -> None:
    manifest = load("artifacts.json")
    entries = [
        manifest["model"],
        manifest["iteration1_model"],
        manifest["candidate_model"],
        manifest["iteration3_model"],
        *manifest["source"].values(),
        *manifest["data"].values(),
    ]
    checked = 0
    for entry in entries:
        path = (HERE / entry["file"]).resolve()
        if not path.exists():
            if entry.get("distributed_in_git") is False:
                print(f"optional artifact absent: {path.name}")
                continue
            raise FileNotFoundError(path)
        actual = sha256(path)
        expected = entry["sha256"].upper()
        if actual != expected:
            raise ValueError(f"SHA-256 mismatch for {path}: {actual} != {expected}")
        if "bytes" in entry and path.stat().st_size != entry["bytes"]:
            raise ValueError(f"size mismatch for {path}")
        print(f"artifact ok: {path.name}")
        checked += 1
    print(f"verified {checked} available artifacts")


def markdown_report() -> str:
    comparison = load("model_comparison.json")
    direct = load("direct_match_summary.json")
    iterations = [
        load("iter1_experiment.json"),
        load("iter2_experiment.json"),
        load("iter3_experiment.json"),
    ]
    swiss = load("swiss_8models_5rounds.json")
    d4_model = load("d4_balanced1m_h16_fromd3_full100_gpu.nnue.json")

    lines = [
        "<!-- Generated by report_results.py; do not edit by hand. -->",
        "# NNUE实验汇总",
        "",
        "## 离线验证",
        "",
        "| 模型 | 教师 | H | 初始化 | 概率MSE | 教师MAE (cp) | 残差相关系数 |",
        "|---|---:|---:|---|---:|---:|---:|",
    ]
    for row in comparison["models"]:
        lines.append(
            f"| {row['name']} | D{row['teacher_depth']} | {row['width']} | "
            f"{row['initialization']} | {row['probability_mse']:.6f} | "
            f"{row['teacher_mae_cp']:.2f} | {row['residual_correlation']:.3f} |"
        )
    for row in comparison["baselines"]:
        lines.append(
            f"| {row['name']} | D{row['teacher_depth']} | — | — | "
            f"{row['probability_mse']:.6f} | {row['teacher_mae_cp']:.2f} | — |"
        )
    for number, iteration in enumerate(iterations, 1):
        student = iteration["student"]
        lines.append(
            f"| Iter{number}-NNUE-D3 | NNUE+D3 | {student['width']} | "
            f"{student['initialization']} | {student['validation_probability_mse']:.6f} | "
            f"{student['validation_teacher_mae_cp']:.2f} | "
            f"{student['validation_residual_correlation']:.3f} |"
        )

    lines += [
        "",
        "## 直接换先对局",
        "",
        "| A | B | A方胜/和/负 | 得分率 | 配对95% CI |",
        "|---|---|---:|---:|---:|",
    ]
    match_rows = [*direct["matches"]]
    for iteration in iterations:
        match_rows.extend(iteration["matches"])
    for row in match_rows:
        lo, hi = row["paired_bootstrap_ci95_percent"]
        lines.append(
            f"| {row['a']} | {row['b']} | "
            f"{row['a_wins']}/{row['draws']}/{row['a_losses']} | "
            f"{row['a_score_percent']:.2f}% | {lo:.2f}%–{hi:.2f}% |"
        )

    lines += [
        "",
        "## 八模型瑞士轮",
        "",
        "| 排名 | 模型 | 盘分 / 盘数 | 得分率 | 胜/和/负 |",
        "|---:|---|---:|---:|---:|",
    ]
    for row in swiss["current_standings"]:
        lines.append(
            f"| {row['rank']} | {row['name']} | {row['game_points']:g}/{row['games']} | "
            f"{row['score_percent']:.2f}% | {row['wins']}/{row['draws']}/{row['losses']} |"
        )

    checkpoints = [
        ("D4-H16-D3init", d4_model),
        ("Iter1-NNUE-D3", load("iter1_nnued3_h16_fromd4_gpu.nnue.json")),
        ("Iter2-NNUE-D3", load("iter2_nnued3_h16_fromiter1_gpu.nnue.json")),
        ("Iter3-NNUE-D3", load("iter3_nnued3_h16_fromiter2_gpu.nnue.json")),
    ]
    lines += ["", "## 最终checkpoint", ""]
    for name, metadata in checkpoints:
        best = min(metadata["history"], key=lambda row: row["validation_objective"])
        lines.append(
            f"- {name}：最佳轮次 {best['epoch']} / {metadata['epochs_completed']}，"
            f"验证目标 {best['validation_objective']:.8f}，K={metadata['k']:.6f}。"
        )
    lines.append("")
    return "\n".join(lines)


def curve_svg(model_file: str, title: str) -> str:
    history = load(model_file)["history"]
    width, height = 900, 480
    left, right, top, bottom = 72, 24, 36, 58
    plot_width, plot_height = width - left - right, height - top - bottom
    values = [row[key] for row in history
              for key in ("train_objective", "validation_objective")]
    low, high = min(values), max(values)
    padding = (high - low) * 0.08 or 0.01
    low, high = low - padding, high + padding

    def x(epoch: int) -> float:
        return left + (epoch - 1) * plot_width / max(1, len(history) - 1)

    def y(value: float) -> float:
        return top + (high - value) * plot_height / (high - low)

    def points(key: str) -> str:
        return " ".join(f"{x(row['epoch']):.1f},{y(row[key]):.1f}" for row in history)

    ticks = []
    for index in range(6):
        value = low + (high - low) * index / 5
        yy = y(value)
        ticks.append(
            f'<line x1="{left}" y1="{yy:.1f}" x2="{width-right}" '
            f'y2="{yy:.1f}" class="grid"/>'
        )
        ticks.append(
            f'<text x="{left-10}" y="{yy+5:.1f}" text-anchor="end">{value:.3f}</text>'
        )
    tick_epochs = sorted({1, len(history), *(
        1 + round(index * (len(history) - 1) / 5) for index in range(1, 5)
    )})
    for epoch in tick_epochs:
        xx = x(epoch)
        ticks.append(
            f'<text x="{xx:.1f}" y="{height-bottom+28}" text-anchor="middle">{epoch}</text>'
        )

    best = min(history, key=lambda row: row["validation_objective"])
    best_x, best_y = x(best["epoch"]), y(best["validation_objective"])
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">
<style>text{{font:14px system-ui,sans-serif;fill:#263238}} .grid{{stroke:#dfe6e9;stroke-width:1}} .axis{{stroke:#607d8b;stroke-width:1.5}} .train{{fill:none;stroke:#1976d2;stroke-width:2.5}} .val{{fill:none;stroke:#d84315;stroke-width:2.5}}</style>
<rect width="100%" height="100%" fill="white"/>
<text x="{left}" y="23" font-size="19" font-weight="600">{title}</text>
{''.join(ticks)}
<line x1="{left}" y1="{top}" x2="{left}" y2="{height-bottom}" class="axis"/><line x1="{left}" y1="{height-bottom}" x2="{width-right}" y2="{height-bottom}" class="axis"/>
<polyline points="{points('train_objective')}" class="train"/><polyline points="{points('validation_objective')}" class="val"/>
<circle cx="{best_x:.1f}" cy="{best_y:.1f}" r="5" fill="#d84315"/><text x="{best_x+9:.1f}" y="{best_y-9:.1f}">最佳验证：第{best['epoch']}轮</text>
<line x1="{width-245}" y1="22" x2="{width-215}" y2="22" class="train"/><text x="{width-207}" y="27">训练集</text>
<line x1="{width-135}" y1="22" x2="{width-105}" y2="22" class="val"/><text x="{width-97}" y="27">验证集</text>
<text x="{width/2}" y="{height-12}" text-anchor="middle">epoch</text><text x="17" y="{height/2}" transform="rotate(-90 17 {height/2})" text-anchor="middle">混合目标</text>
</svg>'''


def iteration_best_validation_svg() -> str:
    models = [
        (0, "NNUE1（PST教师）", load("d4_balanced1m_h16_fromd3_full100_gpu.nnue.json")),
        (1, "教师迭代1", load("iter1_nnued3_h16_fromd4_gpu.nnue.json")),
        (2, "教师迭代2", load("iter2_nnued3_h16_fromiter1_gpu.nnue.json")),
        (3, "教师迭代3", load("iter3_nnued3_h16_fromiter2_gpu.nnue.json")),
    ]
    points = []
    for round_number, name, metadata in models:
        best = min(metadata["history"], key=lambda row: row["validation_objective"])
        points.append((round_number, name, best["validation_objective"], best["epoch"]))
    width, height = 900, 470
    left, right, top, bottom = 92, 35, 55, 100
    plot_width, plot_height = width - left - right, height - top - bottom
    low = min(point[2] for point in points) - 0.002
    high = max(point[2] for point in points) + 0.002

    def x(round_number: int) -> float:
        return left + round_number * plot_width / (len(points) - 1)

    def y(value: float) -> float:
        return top + (high - value) * plot_height / (high - low)

    grid = []
    for index in range(6):
        value = low + (high - low) * index / 5
        yy = y(value)
        grid.append(
            f'<line x1="{left}" y1="{yy:.1f}" x2="{width-right}" '
            f'y2="{yy:.1f}" class="grid"/>'
        )
        grid.append(
            f'<text x="{left-10}" y="{yy+5:.1f}" text-anchor="end">{value:.3f}</text>'
        )
    polyline = " ".join(f"{x(point[0]):.1f},{y(point[2]):.1f}" for point in points)
    marks = []
    for round_number, name, value, epoch in points:
        xx, yy = x(round_number), y(value)
        marks.append(f'<circle cx="{xx:.1f}" cy="{yy:.1f}" r="6" class="point"/>')
        marks.append(
            f'<text x="{xx:.1f}" y="{yy-13:.1f}" text-anchor="middle">'
            f'{value:.5f}（e{epoch}）</text>'
        )
        marks.append(
            f'<text x="{xx:.1f}" y="{height-bottom+28}" text-anchor="middle">'
            f'{name}</text>'
        )
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">
<style>text{{font:14px system-ui,sans-serif;fill:#263238}} .grid{{stroke:#dfe6e9;stroke-width:1}} .axis{{stroke:#607d8b;stroke-width:1.5}} .series{{fill:none;stroke:#6a1b9a;stroke-width:3}} .point{{fill:#8e24aa;stroke:white;stroke-width:2}}</style>
<rect width="100%" height="100%" fill="white"/>
<text x="{left}" y="27" font-size="20" font-weight="600">从PST教师到三轮NNUE教师迭代：最佳验证损失</text>
{''.join(grid)}
<line x1="{left}" y1="{top}" x2="{left}" y2="{height-bottom}" class="axis"/><line x1="{left}" y1="{height-bottom}" x2="{width-right}" y2="{height-bottom}" class="axis"/>
<polyline points="{polyline}" class="series"/>{''.join(marks)}
<text x="{width/2}" y="{height-49}" text-anchor="middle">训练谱系</text>
<text x="19" y="{height/2-20}" transform="rotate(-90 19 {height/2-20})" text-anchor="middle">最佳验证混合目标</text>
<text x="{width/2}" y="{height-19}" text-anchor="middle" fill="#546e7a">各轮教师、数据分布和K不同；该图反映拟合难度，不直接代表棋力。</text>
</svg>'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=HERE / "RESULTS.generated.md")
    parser.add_argument("--curve", type=Path, default=HERE / "training_curve.svg")
    parser.add_argument("--iter1-curve", "--iter-curve", dest="iter1_curve", type=Path,
                        default=HERE / "iter1_training_curve.svg")
    parser.add_argument("--iter2-curve", type=Path,
                        default=HERE / "iter2_training_curve.svg")
    parser.add_argument("--iter3-curve", type=Path,
                        default=HERE / "iter3_training_curve.svg")
    parser.add_argument("--iteration-curve", type=Path,
                        default=HERE / "iteration_best_validation.svg")
    parser.add_argument("--check-artifacts", action="store_true")
    args = parser.parse_args()
    if args.check_artifacts:
        check_artifacts()
    args.output.write_text(markdown_report(), encoding="utf-8")
    args.curve.write_text(curve_svg(
        "d4_balanced1m_h16_fromd3_full100_gpu.nnue.json",
        "D4-H16-D3init 训练曲线"), encoding="utf-8")
    args.iter1_curve.write_text(curve_svg(
        "iter1_nnued3_h16_fromd4_gpu.nnue.json",
        "Iter1-NNUE-D3 训练曲线"), encoding="utf-8")
    args.iter2_curve.write_text(curve_svg(
        "iter2_nnued3_h16_fromiter1_gpu.nnue.json",
        "Iter2-NNUE-D3 训练曲线"), encoding="utf-8")
    args.iter3_curve.write_text(curve_svg(
        "iter3_nnued3_h16_fromiter2_gpu.nnue.json",
        "Iter3-NNUE-D3 训练曲线"), encoding="utf-8")
    args.iteration_curve.write_text(iteration_best_validation_svg(), encoding="utf-8")
    for path in (args.output, args.curve, args.iter1_curve, args.iter2_curve,
                 args.iter3_curve, args.iteration_curve):
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
