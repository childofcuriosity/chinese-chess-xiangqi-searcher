"""Generate the checked-in NNUE result tables and a dependency-free SVG curve."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent


def load(name: str):
    return json.loads((HERE / name).read_text(encoding="utf-8"))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest().upper()


def check_artifacts() -> None:
    manifest = load("artifacts.json")
    entries = [manifest["model"], *manifest["source"].values(),
               *manifest["data"].values()]
    checked = 0
    for entry in entries:
        path = (HERE / entry["file"]).resolve()
        if not path.exists():
            if entry.get("distributed_in_git") is False:
                print(f"optional artifact absent: {path.name}")
                continue
            raise FileNotFoundError(path)
        actual = sha256(path)
        expected = entry["sha256"].upper()
        if actual != expected:
            raise ValueError(f"SHA-256 mismatch for {path}: {actual} != {expected}")
        if "bytes" in entry and path.stat().st_size != entry["bytes"]:
            raise ValueError(f"size mismatch for {path}")
        print(f"artifact ok: {path.name}")
        checked += 1
    print(f"verified {checked} available artifacts")


def fmt(value, digits=2):
    return f"{value:.{digits}f}"


def markdown_report() -> str:
    comparison = load("model_comparison.json")
    direct = load("direct_match_summary.json")
    swiss = load("swiss_8models_5rounds.json")
    model = load("d4_balanced1m_h16_fromd3_full100_gpu.nnue.json")

    lines = [
        "<!-- Generated by report_results.py; do not edit by hand. -->",
        "# NNUE实验汇总",
        "",
        "## 离线验证",
        "",
        "| 模型 | 教师 | H | 初始化 | 概率MSE | 教师MAE (cp) | 残差相关系数 |",
        "|---|---:|---:|---|---:|---:|---:|",
    ]
    for row in comparison["models"]:
        lines.append(
            f"| {row['name']} | D{row['teacher_depth']} | {row['width']} | "
            f"{row['initialization']} | {row['probability_mse']:.6f} | "
            f"{row['teacher_mae_cp']:.2f} | {row['residual_correlation']:.3f} |"
        )
    for row in comparison["baselines"]:
        lines.append(
            f"| {row['name']} | D{row['teacher_depth']} | — | — | "
            f"{row['probability_mse']:.6f} | {row['teacher_mae_cp']:.2f} | — |"
        )

    lines += [
        "",
        "## 直接换先对局",
        "",
        "| A | B | A方胜/和/负 | 得分率 | 配对95% CI |",
        "|---|---|---:|---:|---:|",
    ]
    for row in direct["matches"]:
        lo, hi = row["paired_bootstrap_ci95_percent"]
        lines.append(
            f"| {row['a']} | {row['b']} | {row['a_wins']}/{row['draws']}/{row['a_losses']} | "
            f"{row['a_score_percent']:.2f}% | {lo:.2f}%–{hi:.2f}% |"
        )

    standings = swiss["current_standings"]
    lines += [
        "",
        "## 八模型瑞士轮",
        "",
        "| 排名 | 模型 | 盘分 / 盘数 | 得分率 | 胜/和/负 |",
        "|---:|---|---:|---:|---:|",
    ]
    for row in standings:
        lines.append(
            f"| {row['rank']} | {row['name']} | {row['game_points']:g}/{row['games']} | "
            f"{row['score_percent']:.2f}% | {row['wins']}/{row['draws']}/{row['losses']} |"
        )

    history = model["history"]
    best = min(history, key=lambda row: row["validation_objective"])
    lines += [
        "",
        "## 最终checkpoint",
        "",
        f"- 模型：D4-H16-D3init；最佳轮次 {best['epoch']} / {model['epochs_completed']}。",
        f"- 最佳验证目标：{best['validation_objective']:.8f}。",
        f"- 最终训练目标：{history[-1]['train_objective']:.8f}。",
        f"- 冻结K：{model['k']:.6f}；定点输出scale：{model['output_scale']:g}。",
        "",
    ]
    return "\n".join(lines)


def curve_svg() -> str:
    history = load("d4_balanced1m_h16_fromd3_full100_gpu.nnue.json")["history"]
    width, height = 900, 480
    left, right, top, bottom = 72, 24, 36, 58
    pw, ph = width - left - right, height - top - bottom
    values = [r[k] for r in history for k in ("train_objective", "validation_objective")]
    lo, hi = min(values), max(values)
    pad = (hi - lo) * 0.08 or 0.01
    lo, hi = lo - pad, hi + pad

    def x(epoch):
        return left + (epoch - 1) * pw / max(1, len(history) - 1)

    def y(value):
        return top + (hi - value) * ph / (hi - lo)

    def points(key):
        return " ".join(f"{x(r['epoch']):.1f},{y(r[key]):.1f}" for r in history)

    ticks = []
    for i in range(6):
        value = lo + (hi - lo) * i / 5
        yy = y(value)
        ticks.append(f'<line x1="{left}" y1="{yy:.1f}" x2="{width-right}" y2="{yy:.1f}" class="grid"/>')
        ticks.append(f'<text x="{left-10}" y="{yy+5:.1f}" text-anchor="end">{value:.3f}</text>')
    for epoch in (1, 20, 40, 60, 80, 100):
        xx = x(epoch)
        ticks.append(f'<text x="{xx:.1f}" y="{height-bottom+28}" text-anchor="middle">{epoch}</text>')

    best = min(history, key=lambda row: row["validation_objective"])
    bx, by = x(best["epoch"]), y(best["validation_objective"])
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">
<style>text{{font:14px system-ui,sans-serif;fill:#263238}} .grid{{stroke:#dfe6e9;stroke-width:1}} .axis{{stroke:#607d8b;stroke-width:1.5}} .train{{fill:none;stroke:#1976d2;stroke-width:2.5}} .val{{fill:none;stroke:#d84315;stroke-width:2.5}}</style>
<rect width="100%" height="100%" fill="white"/>
<text x="{left}" y="23" font-size="19" font-weight="600">D4-H16-D3init 训练曲线</text>
{''.join(ticks)}
<line x1="{left}" y1="{top}" x2="{left}" y2="{height-bottom}" class="axis"/><line x1="{left}" y1="{height-bottom}" x2="{width-right}" y2="{height-bottom}" class="axis"/>
<polyline points="{points('train_objective')}" class="train"/><polyline points="{points('validation_objective')}" class="val"/>
<circle cx="{bx:.1f}" cy="{by:.1f}" r="5" fill="#d84315"/><text x="{bx+9:.1f}" y="{by-9:.1f}">最佳验证：第{best['epoch']}轮</text>
<line x1="{width-245}" y1="22" x2="{width-215}" y2="22" class="train"/><text x="{width-207}" y="27">训练集</text>
<line x1="{width-135}" y1="22" x2="{width-105}" y2="22" class="val"/><text x="{width-97}" y="27">验证集</text>
<text x="{width/2}" y="{height-12}" text-anchor="middle">epoch</text><text x="17" y="{height/2}" transform="rotate(-90 17 {height/2})" text-anchor="middle">混合目标</text>
</svg>'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=HERE / "RESULTS.generated.md")
    parser.add_argument("--curve", type=Path, default=HERE / "training_curve.svg")
    parser.add_argument("--check-artifacts", action="store_true")
    args = parser.parse_args()
    if args.check_artifacts:
        check_artifacts()
    args.output.write_text(markdown_report(), encoding="utf-8")
    args.curve.write_text(curve_svg(), encoding="utf-8")
    print(f"wrote {args.output}")
    print(f"wrote {args.curve}")


if __name__ == "__main__":
    main()
